#!/usr/bin/env python3
"""Generate the Minecraft 1.21.11 to 26.3 entity and block-entity ID maps."""

import argparse
import json
from pathlib import Path


def registry_ids(report, registry):
    return {
        name: entry["protocol_id"]
        for name, entry in report[f"minecraft:{registry}"]["entries"].items()
    }


def render(name, kind, entries):
    lines = ["#[rustfmt::skip]", f"pub(super) const {name}: [{kind}; {len(entries)}] = ["]
    for offset in range(0, len(entries), 12):
        lines.append("    " + ", ".join(entries[offset:offset + 12]) + ",")
    return [*lines, "];"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="1.21.11 registries.json")
    parser.add_argument("target", type=Path, help="26.3 registries.json")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    reports = [json.loads(path.read_text()) for path in (args.source, args.target)]
    source, target = (registry_ids(report, "entity_type") for report in reports)
    if sorted(source.values()) != list(range(157)) or sorted(target.values()) != list(range(161)):
        raise ValueError("expected the vanilla 1.21.11 and 26.3 entity registries")
    if missing := source.keys() - target.keys():
        raise ValueError(f"unmapped source entities: {', '.join(sorted(missing))}")
    entities = [str(target[name]) for name in sorted(source, key=source.__getitem__)]
    lines = [
        "// Generated by tools/generate_radio_entity_map.py from vanilla registries.json.",
        f"pub(super) const FALLING_BLOCK: i32 = {source['minecraft:falling_block']};",
        *render("ENTITY_TYPES", "u8", entities),
    ]

    source, target = (registry_ids(report, "block_entity_type") for report in reports)
    if any(sorted(table.values()) != list(range(49)) for table in (source, target)):
        raise ValueError("expected the vanilla 1.21.11 and 26.3 block entity registries")
    if source.keys() - target.keys() != {"minecraft:bed"}:
        raise ValueError("unexpected block entity was removed")
    block_entities = [
        f"Some({target[name]})" if name in target else "None"
        for name in sorted(source, key=source.__getitem__)
    ]
    lines.extend(["", *render("BLOCK_ENTITY_TYPES", "Option<u8>", block_entities)])
    args.output.write_text("\n".join([*lines, ""]))


if __name__ == "__main__":
    main()
