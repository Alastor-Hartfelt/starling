#!/usr/bin/env python3
"""Generate the Minecraft 1.21.11 to 26.3 entity-type ID map."""

import argparse
import json
from pathlib import Path


def entity_types(report):
    return {
        name: entry["protocol_id"]
        for name, entry in json.loads(report.read_text())["minecraft:entity_type"]["entries"].items()
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="1.21.11 registries.json")
    parser.add_argument("target", type=Path, help="26.3 registries.json")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    source, target = entity_types(args.source), entity_types(args.target)
    if sorted(source.values()) != list(range(157)) or sorted(target.values()) != list(range(161)):
        raise ValueError("expected the vanilla 1.21.11 and 26.3 entity registries")
    if missing := source.keys() - target.keys():
        raise ValueError(f"unmapped source entities: {', '.join(sorted(missing))}")
    ids = [target[name] for name in sorted(source, key=source.__getitem__)]
    lines = [
        "// Generated by tools/generate_radio_entity_map.py from vanilla registries.json.",
        f"pub(super) const FALLING_BLOCK: i32 = {source['minecraft:falling_block']};",
        "#[rustfmt::skip]",
        f"pub(super) const ENTITY_TYPES: [u8; {len(ids)}] = [",
    ]
    for offset in range(0, len(ids), 12):
        lines.append("    " + ", ".join(map(str, ids[offset:offset + 12])) + ",")
    args.output.write_text("\n".join([*lines, "];", ""]))


if __name__ == "__main__":
    main()
