#!/usr/bin/env python3
"""Generate the Minecraft 1.21.11 to 26.3 item and component ID maps."""

import argparse
import json
from pathlib import Path
from generate_radio_entity_map import registry_ids, render


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="1.21.11 registries.json")
    parser.add_argument("target", type=Path, help="26.3 registries.json")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    reports = [json.loads(path.read_text()) for path in (args.source, args.target)]
    output = ["// Generated by tools/generate_radio_item_map.py from vanilla registries.json."]
    registries = (
        ("item", "ITEMS", (1505, 1658), set()),
        ("data_component_type", "COMPONENTS", (104, 122),
         {"minecraft:map_color", "minecraft:swing_animation"}),
    )
    for registry, label, sizes, removed in registries:
        source, target = (registry_ids(report, registry) for report in reports)
        if (sorted(source.values()), sorted(target.values())) != tuple(list(range(n)) for n in sizes):
            raise ValueError(f"unexpected vanilla {registry} registry")
        if source.keys() - target.keys() != removed:
            raise ValueError(f"unexpected removed {registry} entries")
        entries = [str(target.get(name, -1)) for name in sorted(source, key=source.__getitem__)]
        output.extend(render(label, "i16", entries))
        output.append("")
    args.output.write_text("\n".join(output))


if __name__ == "__main__":
    main()
