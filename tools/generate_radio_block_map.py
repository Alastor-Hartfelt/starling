#!/usr/bin/env python3
"""Generate the Radio block-state ID map from vanilla 1.21.11 and 26.3 blocks.json reports."""

import argparse
import json
from pathlib import Path


def states(path):
    report = json.loads(path.read_text())
    result = {}
    for name, block in report.items():
        for state in block["states"]:
            key = (name, tuple(sorted(state.get("properties", {}).items())))
            if key in result:
                raise ValueError(f"{path}: duplicate block state {key}")
            result[key] = state["id"]
    if sorted(result.values()) != list(range(len(result))):
        raise ValueError(f"{path}: block IDs must be unique and contiguous")
    return result


def first_states_by_block_id(registries, states_by_key):
    entries = json.loads(registries.read_text())["minecraft:block"]["entries"]
    first = {}
    for (name, _), state_id in states_by_key.items():
        first[name] = min(first.get(name, state_id), state_id)
    if set(first) != set(entries):
        raise ValueError("source block and registry reports list different blocks")
    block_ids = {entry["protocol_id"]: name for name, entry in entries.items()}
    if sorted(block_ids) != list(range(len(first))):
        raise ValueError("source block registry IDs must be unique and contiguous")
    return [first[block_ids[i]] for i in range(len(first))]


def format_block_events(states):
    lines = [
        "",
        "// First 1.21.11 state ID for each 1.21.11 block registry ID.",
        "#[rustfmt::skip]",
        "pub(super) const BLOCK_EVENT_STATES: &[u16] = &[",
    ]
    for i in range(0, len(states), 12):
        lines.append("    " + ", ".join(map(str, states[i:i + 12])) + ",")
    lines.append("];")
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="1.21.11 generated/reports/blocks.json")
    parser.add_argument("target", type=Path, help="26.3 generated/reports/blocks.json")
    parser.add_argument("output", type=Path, help="Rust file to generate")
    args = parser.parse_args()
    source, target = states(args.source), states(args.target)
    if (len(source), len(target)) != (29671, 35723):
        raise ValueError("unexpected report sizes for vanilla 1.21.11 and 26.3")
    missing = source.keys() - target.keys()
    if missing:
        raise ValueError(f"{len(missing)} source block states have no exact match: {min(missing)}")

    by_id = [target[key] for key in sorted(source, key=source.__getitem__)]
    starts = [(i, value) for i, value in enumerate(by_id) if i == 0 or by_id[i - 1] + 1 != value]
    lines = [
        "// Generated by tools/generate_radio_block_map.py from the vanilla block reports.",
        f"pub(super) const SOURCE_LEN: usize = {len(source)};",
        f"pub(super) const SOURCE_BITS: u8 = {(len(source) - 1).bit_length()};",
        f"pub(super) const TARGET_BITS: u8 = {(len(target) - 1).bit_length()};",
        "",
        "// (first 1.21.11 ID, first 26.3 ID) for each run of consecutive IDs.",
        "pub(super) const STARTS: &[(u16, u16)] = &[",
    ]
    lines.extend(f"    ({old}, {new})," for old, new in starts)
    lines.append("];")
    lines.extend(format_block_events(first_states_by_block_id(
        args.source.with_name("registries.json"), source
    )))
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
